--Trigger kiểm soát thời gian điểm danh
CREATE OR REPLACE TRIGGER TRG_CHECK_THOI_GIAN_DIEMDANH
BEFORE INSERT ON LICHSU_DIEMDANH
FOR EACH ROW
DECLARE
    v_ngay DATE; v_gio_bd VARCHAR2(10); v_gio_kt VARCHAR2(10);
    v_now VARCHAR2(5);
BEGIN
    SELECT NGAY_HOC, GIO_BAT_DAU, GIO_KET_THUC 
    INTO v_ngay, v_gio_bd, v_gio_kt
    FROM LICH_HOC WHERE MA_BUOI_HOC = :NEW.MA_BUOI_HOC;
    
    v_now := TO_CHAR(SYSDATE, 'HH24:MI');
    
    IF TRUNC(SYSDATE) <> v_ngay THEN
        RAISE_APPLICATION_ERROR(-20001, 'Không phải ngày học!');
    END IF;
    
    IF v_now < v_gio_bd OR v_now > v_gio_kt THEN
        RAISE_APPLICATION_ERROR(-20002, 'Chưa đến giờ hoặc đã hết giờ!');
    END IF;
END;
/

-- Trigger giám sát người dùng (thêm, xóa, sửa)
CREATE OR REPLACE TRIGGER TRG_AUDIT_USER_CHANGES
AFTER INSERT OR UPDATE OR DELETE ON NGUOI_DUNG
FOR EACH ROW
DECLARE 
    v_user VARCHAR2(50);
BEGIN
    SELECT USER INTO v_user FROM DUAL; 
    
    IF INSERTING THEN
        INSERT INTO LOG_DB_CHANGES (USER_DB, ACTION_TYPE, TABLE_NAME, NEW_DATA)
        VALUES (v_user, 'INSERT', 'NGUOI_DUNG', 'New User: ' || :NEW.TEN_DANG_NHAP || ' (' || :NEW.HO_TEN || ')');
        
    ELSIF UPDATING THEN
        INSERT INTO LOG_DB_CHANGES (USER_DB, ACTION_TYPE, TABLE_NAME, OLD_DATA, NEW_DATA)
        VALUES (v_user, 'UPDATE', 'NGUOI_DUNG', 
                'User: ' || :OLD.TEN_DANG_NHAP, 
                'Updated Info (Role/Email/Pass)');
                
    ELSIF DELETING THEN
        INSERT INTO LOG_DB_CHANGES (USER_DB, ACTION_TYPE, TABLE_NAME, OLD_DATA)
        VALUES (v_user, 'DELETE', 'NGUOI_DUNG', 'Deleted User: ' || :OLD.TEN_DANG_NHAP || ' - ID: ' || :OLD.MA_NGUOI_DUNG);
    END IF;
END;
/

