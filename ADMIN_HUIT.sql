-- View Audit Log của ứng dụng (từ bảng AUDIT_LOG)
CREATE OR REPLACE VIEW V_APP_AUDIT_LOG AS
SELECT 
    a.THOI_GIAN,
    u.HO_TEN,
    u.TEN_DANG_NHAP,
    a.HANH_DONG,
    a.CHI_TIET,
    a.IP_ADDRESS,
    a.TRANG_THAI
FROM AUDIT_LOG a
LEFT JOIN NGUOI_DUNG u ON a.MA_NGUOI_DUNG = u.MA_NGUOI_DUNG
ORDER BY a.THOI_GIAN DESC;

-- View Database Changes (từ trigger)
CREATE OR REPLACE VIEW V_DB_AUDIT AS
SELECT 
    ID_LOG,
    USER_DB,
    ACTION_TIME,
    ACTION_TYPE,
    TABLE_NAME,
    OLD_DATA,
    NEW_DATA
FROM LOG_DB_CHANGES
ORDER BY ACTION_TIME DESC;

-- View tổng hợp hoạt động điểm danh
CREATE OR REPLACE VIEW V_DIEMDANH_ACTIVITY AS
SELECT 
    l.THOI_GIAN_DIEM_DANH,
    sv.HO_TEN as SINH_VIEN,
    sv.TEN_DANG_NHAP as MSSV,
    mh.TEN_MON,
    gv.HO_TEN as GIANG_VIEN,
    l.PHUONG_THUC,
    l.TRANG_THAI,
    lh.PHONG_HOC
FROM LICHSU_DIEMDANH l
JOIN NGUOI_DUNG sv ON l.MA_SINH_VIEN = sv.MA_NGUOI_DUNG
JOIN LICH_HOC lh ON l.MA_BUOI_HOC = lh.MA_BUOI_HOC
JOIN LOP_HOC_PHAN lhp ON lh.MA_LOP_HP = lhp.MA_LOP_HP
JOIN MON_HOC mh ON lhp.MA_MON = mh.MA_MON
JOIN NGUOI_DUNG gv ON lhp.MA_GIANG_VIEN = gv.MA_NGUOI_DUNG
ORDER BY l.THOI_GIAN_DIEM_DANH DESC;

-- View thống kê bảo mật
CREATE OR REPLACE VIEW V_SECURITY_STATS AS
SELECT 
    (SELECT COUNT(*) FROM AUDIT_LOG WHERE TRANG_THAI = N'Thành công') as LOGIN_SUCCESS,
    (SELECT COUNT(*) FROM AUDIT_LOG WHERE TRANG_THAI = N'Thất bại') as LOGIN_FAILED,
    (SELECT COUNT(*) FROM LOG_DB_CHANGES WHERE ACTION_TYPE = 'INSERT') as TOTAL_INSERTS,
    (SELECT COUNT(*) FROM LOG_DB_CHANGES WHERE ACTION_TYPE = 'UPDATE') as TOTAL_UPDATES,
    (SELECT COUNT(*) FROM LOG_DB_CHANGES WHERE ACTION_TYPE = 'DELETE') as TOTAL_DELETES,
    (SELECT COUNT(*) FROM LICHSU_DIEMDANH WHERE TRUNC(THOI_GIAN_DIEM_DANH) = TRUNC(SYSDATE)) as TODAY_ATTENDANCE
FROM DUAL;



