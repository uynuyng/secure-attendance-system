    FUNCTION HYBRID_DECRYPT(p_private_key_enc IN CLOB, p_encrypted_data IN RAW, p_encrypted_aes_key IN RAW) RETURN VARCHAR2;
END PKG_MAHOA_LAI;
/

-- 2. PACKAGE BODY - TRIỂN KHAI MÃ HÓA LAI
CREATE OR REPLACE PACKAGE BODY PKG_MAHOA_LAI IS
    
    G_MASTER_KEY RAW(32) := UTL_RAW.CAST_TO_RAW('4B686F6142694D6174436F446F416E21');
    
    FUNCTION DERIVE_AES128_KEY(p_input IN RAW) RETURN RAW IS
        v_hash RAW(32);
        v_key RAW(16);
    BEGIN
        v_hash := DBMS_CRYPTO.HASH(p_input, DBMS_CRYPTO.HASH_SH256);
        v_key := UTL_RAW.SUBSTR(v_hash, 1, 16);
        RETURN v_key;
    END DERIVE_AES128_KEY;
    
    -- Tạo cặp khóa RSA 
    PROCEDURE GEN_RSA_KEYPAIR(
        p_ma_nguoi_dung IN NUMBER,
        p_out_public_key OUT CLOB,
        p_out_private_key OUT CLOB
    ) IS
        v_modulus RAW(128);             
        v_exponent RAW(4) := HEXTORAW('00010001');  
        v_private_exp RAW(128);          
        v_public_key_raw RAW(200);       
        v_private_key_raw RAW(300);      
        v_private_key_encrypted RAW(2000);
        v_public_key_hex VARCHAR2(500);  -- SỬ DỤNG VARCHAR2 TRƯỚC
        v_private_key_hex VARCHAR2(4000);
    BEGIN
        v_modulus := DBMS_CRYPTO.RANDOMBYTES(128);
        v_private_exp := DBMS_CRYPTO.RANDOMBYTES(128);
        
        -- Tạo Public Key
        v_public_key_raw := UTL_RAW.CONCAT(v_modulus, v_exponent);
        v_public_key_hex := RAWTOHEX(v_public_key_raw);
        
        -- Chuyển sang CLOB an toàn
        DBMS_LOB.CREATETEMPORARY(p_out_public_key, TRUE);
        DBMS_LOB.WRITEAPPEND(p_out_public_key, LENGTH(v_public_key_hex), v_public_key_hex);
        
        -- Tạo Private Key và mã hóa
        v_private_key_raw := UTL_RAW.CONCAT(v_modulus, v_private_exp);
        v_private_key_encrypted := DBMS_CRYPTO.ENCRYPT(
            src => v_private_key_raw,
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => G_MASTER_KEY
        );
        v_private_key_hex := RAWTOHEX(v_private_key_encrypted);
        
        -- Chuyển sang CLOB an toàn
        DBMS_LOB.CREATETEMPORARY(p_out_private_key, TRUE);
        DBMS_LOB.WRITEAPPEND(p_out_private_key, LENGTH(v_private_key_hex), v_private_key_hex);
        
        -- Lưu vào database
        UPDATE NGUOI_DUNG 
        SET PUBLIC_KEY = p_out_public_key,
            PRIVATE_KEY_ENC = p_out_private_key
        WHERE MA_NGUOI_DUNG = p_ma_nguoi_dung;
        
        COMMIT;
        
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('Lỗi tạo khóa cho user ' || p_ma_nguoi_dung || ': ' || SQLERRM);
            ROLLBACK;
            RAISE;
    END GEN_RSA_KEYPAIR;
    
    -- Mã hóa bằng RSA Public Key
    FUNCTION ENCRYPT_WITH_PUBLIC_KEY(
        p_public_key IN CLOB,
        p_data IN VARCHAR2
    ) RETURN RAW IS
        v_public_key_hex VARCHAR2(1000);
        v_public_key_raw RAW(500);
        v_data_raw RAW(2000);
        v_key_hash RAW(32);
    BEGIN
        IF p_public_key IS NULL OR p_data IS NULL THEN
            RETURN NULL;
        END IF;
        
        -- Chuyển CLOB → VARCHAR2 → RAW an toàn
        v_public_key_hex := DBMS_LOB.SUBSTR(p_public_key, 1000, 1);
        v_public_key_raw := HEXTORAW(v_public_key_hex);
        v_data_raw := UTL_I18N.STRING_TO_RAW(p_data, 'AL32UTF8');
        
        -- Hash public key để làm encryption key
        v_key_hash := DBMS_CRYPTO.HASH(v_public_key_raw, DBMS_CRYPTO.HASH_SH256);
        
        -- Mã hóa dữ liệu
        RETURN DBMS_CRYPTO.ENCRYPT(
            src => v_data_raw,
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => v_key_hash
        );
        
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('Lỗi mã hóa RSA: ' || SQLERRM);
            RETURN NULL;
    END ENCRYPT_WITH_PUBLIC_KEY;
    
    -- Giải mã bằng RSA Private Key
    FUNCTION DECRYPT_WITH_PRIVATE_KEY(
        p_private_key_enc IN CLOB,
        p_encrypted_data IN RAW
    ) RETURN VARCHAR2 IS
        v_private_key_hex VARCHAR2(4000);
        v_private_key_enc_raw RAW(2000);
        v_private_key_raw RAW(500);
        v_key_hash RAW(32);
        v_decrypted_data RAW(2000);
    BEGIN
        IF p_private_key_enc IS NULL OR p_encrypted_data IS NULL THEN
            RETURN NULL;
        END IF;
        
        v_private_key_hex := DBMS_LOB.SUBSTR(p_private_key_enc, 4000, 1);
        v_private_key_enc_raw := HEXTORAW(v_private_key_hex);
        
        v_private_key_raw := DBMS_CRYPTO.DECRYPT(
            src => v_private_key_enc_raw,
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => G_MASTER_KEY
        );
        
        -- Hash private key để làm decryption key
        v_key_hash := DBMS_CRYPTO.HASH(v_private_key_raw, DBMS_CRYPTO.HASH_SH256);
        v_decrypted_data := DBMS_CRYPTO.DECRYPT(
            src => p_encrypted_data,
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => v_key_hash
        );
        
        RETURN UTL_I18N.RAW_TO_CHAR(v_decrypted_data, 'AL32UTF8');
        
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('Lỗi giải mã RSA: ' || SQLERRM);
            RETURN NULL;
    END DECRYPT_WITH_PRIVATE_KEY;
    
    -- MÃ HÓA LAI: AES + RSA
    FUNCTION HYBRID_ENCRYPT(
        p_public_key IN CLOB,
        p_data IN VARCHAR2,
        p_out_encrypted_aes_key OUT RAW
    ) RETURN RAW IS
        v_aes_key RAW(32);
        v_encrypted_data RAW(32767);
    BEGIN
        IF p_public_key IS NULL OR p_data IS NULL THEN
            RETURN NULL;
        END IF;
        
        v_aes_key := DBMS_CRYPTO.RANDOMBYTES(32);
        
        v_encrypted_data := DBMS_CRYPTO.ENCRYPT(
            src => UTL_I18N.STRING_TO_RAW(p_data, 'AL32UTF8'),
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => v_aes_key
        );
        p_out_encrypted_aes_key := ENCRYPT_WITH_PUBLIC_KEY(
            p_public_key, 
            RAWTOHEX(v_aes_key)
        );
        
        RETURN v_encrypted_data;
        
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('Lỗi mã hóa lai: ' || SQLERRM);
            RETURN NULL;
    END HYBRID_ENCRYPT;
    
    -- GIẢI MÃ LAI
    FUNCTION HYBRID_DECRYPT(
        p_private_key_enc IN CLOB,
        p_encrypted_data IN RAW,
        p_encrypted_aes_key IN RAW
    ) RETURN VARCHAR2 IS
        v_aes_key_hex VARCHAR2(100);
        v_aes_key RAW(32);
        v_decrypted_data RAW(32767);
    BEGIN
        IF p_private_key_enc IS NULL OR p_encrypted_data IS NULL OR p_encrypted_aes_key IS NULL THEN
            RETURN NULL;
        END IF;
        v_aes_key_hex := DECRYPT_WITH_PRIVATE_KEY(
            p_private_key_enc, 
            p_encrypted_aes_key
        );
        
        IF v_aes_key_hex IS NULL THEN
            RETURN NULL;
        END IF;
        
        v_aes_key := HEXTORAW(v_aes_key_hex);
        v_decrypted_data := DBMS_CRYPTO.DECRYPT(
            src => p_encrypted_data,
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => v_aes_key
        );
        
        RETURN UTL_I18N.RAW_TO_CHAR(v_decrypted_data, 'AL32UTF8');
        
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('Lỗi giải mã lai: ' || SQLERRM);
            RETURN NULL;
    END HYBRID_DECRYPT;
    
END PKG_MAHOA_LAI;
