--Thêm người dùng 
CREATE OR REPLACE PROCEDURE PROC_THEM_NGUOI_DUNG_AUTO (
    p_name IN NVARCHAR2, 
    p_email IN VARCHAR2, 
    p_role IN NUMBER
) IS
    v_salt VARCHAR2(100); 
    v_hash VARCHAR2(255);
    v_prefix VARCHAR2(5);
    v_next_id NUMBER;
    v_new_username VARCHAR2(50);
BEGIN
    -- Xác định tiền tố là sinh viên hay giảng viên 
    IF p_role = 2 THEN v_prefix := 'GV'; ELSE v_prefix := 'SV'; END IF;
    -- Tìm số thứ tự tiếp theo
    BEGIN
        SELECT NVL(MAX(TO_NUMBER(SUBSTR(TEN_DANG_NHAP, 3))), 0) + 1 
        INTO v_next_id FROM NGUOI_DUNG WHERE TEN_DANG_NHAP LIKE v_prefix || '%';
    EXCEPTION WHEN OTHERS THEN v_next_id := 1; END;
    -- Tạo Username
    v_new_username := v_prefix || LPAD(v_next_id, 3, '0');

    -- Tạo mật khẩu cố định '123'
    v_salt := FUNC_GEN_SALT();    
    v_hash := FUNC_HASH_PASS('123', v_salt);
    INSERT INTO NGUOI_DUNG (
        TEN_DANG_NHAP, MAT_KHAU_HASH, SALT, HO_TEN, EMAIL, MA_VAI_TRO, FORCE_CHANGE_PASS
    ) VALUES (
        v_new_username, v_hash, v_salt, p_name, p_email, p_role, 1
    );
    COMMIT;
END;
/

