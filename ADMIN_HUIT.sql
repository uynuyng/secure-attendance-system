-- 5. PROCEDURE ĐIỂM DANH VỚI MÃ HÓA LAI
CREATE OR REPLACE PROCEDURE PROC_DIEMDANH_HYBRID(
    p_ma_buoi_hoc IN NUMBER,
    p_ma_sinh_vien IN NUMBER,
    p_phuong_thuc IN VARCHAR2,
    p_thiet_bi IN VARCHAR2,
    p_vi_tri IN VARCHAR2,
    p_trang_thai IN NVARCHAR2
) IS
    v_public_key CLOB;
    v_thiet_bi_enc RAW(32767);
    v_vi_tri_enc RAW(32767);
    v_aes_key_enc RAW(2000);
BEGIN
    -- Lấy Public Key của sinh viên
    SELECT PUBLIC_KEY INTO v_public_key 
    FROM NGUOI_DUNG 
    WHERE MA_NGUOI_DUNG = p_ma_sinh_vien;
    
    IF v_public_key IS NULL THEN
        RAISE_APPLICATION_ERROR(-20010, 'User chưa có RSA keypair!');
    END IF;
    
    -- Mã hóa THIET_BI bằng Hybrid Encryption
    v_thiet_bi_enc := PKG_MAHOA_LAI.HYBRID_ENCRYPT(
        v_public_key, 
        p_thiet_bi, 
        v_aes_key_enc
    );
    
    -- Mã hóa VI_TRI bằng Hybrid Encryption (tạo AES key mới)
    v_vi_tri_enc := PKG_MAHOA_LAI.HYBRID_ENCRYPT(
        v_public_key, 
        p_vi_tri, 
        v_aes_key_enc 
    );
    
    -- Lưu vào database
    INSERT INTO LICHSU_DIEMDANH (
        MA_BUOI_HOC, 
        MA_SINH_VIEN, 
        PHUONG_THUC, 
        TRANG_THAI,
        THIET_BI_ENC,
        VI_TRI_ENC,
        ENCRYPTED_AES_KEY
    ) VALUES (
        p_ma_buoi_hoc, 
        p_ma_sinh_vien, 
        p_phuong_thuc, 
        p_trang_thai,
        v_thiet_bi_enc,
        v_vi_tri_enc,
        v_aes_key_enc
    );
    COMMIT;
END;
/

-- 6. FUNCTION ĐỌC DỮ LIỆU ĐÃ MÃ HÓA LAI
CREATE OR REPLACE FUNCTION FUNC_GIAIMA_DIEMDANH(
    p_ma_log IN NUMBER,
    p_loai_du_lieu IN VARCHAR2 
) RETURN VARCHAR2 IS
    v_private_key_enc CLOB;
    v_encrypted_data RAW(32767);
    v_encrypted_aes_key RAW(2000);
    v_result VARCHAR2(4000);
BEGIN
    -- Lấy Private Key của sinh viên và dữ liệu mã hóa
    SELECT nd.PRIVATE_KEY_ENC, 
           CASE 
               WHEN p_loai_du_lieu = 'THIET_BI' THEN ls.THIET_BI_ENC
               ELSE ls.VI_TRI_ENC
           END,
           ls.ENCRYPTED_AES_KEY
    INTO v_private_key_enc, v_encrypted_data, v_encrypted_aes_key
    FROM LICHSU_DIEMDANH ls
    JOIN NGUOI_DUNG nd ON ls.MA_SINH_VIEN = nd.MA_NGUOI_DUNG
    WHERE ls.MA_LOG = p_ma_log;
    
    -- Giải mã bằng Hybrid Decryption
    v_result := PKG_MAHOA_LAI.HYBRID_DECRYPT(
        v_private_key_enc,
        v_encrypted_data,
        v_encrypted_aes_key
    );
    
    RETURN v_result;
END;
