    );
    FUNCTION ENCRYPT_WITH_PUBLIC_KEY(p_public_key IN CLOB, p_data IN VARCHAR2) RETURN RAW;
    FUNCTION DECRYPT_WITH_PRIVATE_KEY(p_private_key_enc IN CLOB, p_encrypted_data IN RAW) RETURN VARCHAR2;
