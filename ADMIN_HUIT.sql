--TRIGGER AUDIT
CREATE OR REPLACE TRIGGER TRG_AUDIT_DB
AFTER INSERT OR UPDATE OR DELETE ON LICHSU_DIEMDANH
FOR EACH ROW
DECLARE v_user VARCHAR2(50);
BEGIN
    SELECT USER INTO v_user FROM DUAL; 
    
    IF INSERTING THEN
        INSERT INTO LOG_DB_CHANGES (USER_DB, ACTION_TYPE, TABLE_NAME, NEW_DATA)
        VALUES (v_user, 'INSERT', 'LICHSU_DIEMDANH', 'SV:' || :NEW.MA_SINH_VIEN || ' - TT:' || :NEW.TRANG_THAI);
    ELSIF UPDATING THEN
        INSERT INTO LOG_DB_CHANGES (USER_DB, ACTION_TYPE, TABLE_NAME, OLD_DATA, NEW_DATA)
        VALUES (v_user, 'UPDATE', 'LICHSU_DIEMDANH', 
                'Old TT:' || :OLD.TRANG_THAI, 'New TT:' || :NEW.TRANG_THAI);
    ELSIF DELETING THEN
        INSERT INTO LOG_DB_CHANGES (USER_DB, ACTION_TYPE, TABLE_NAME, OLD_DATA)
        VALUES (v_user, 'DELETE', 'LICHSU_DIEMDANH', 'Del SV:' || :OLD.MA_SINH_VIEN);
    END IF;
END;
/

